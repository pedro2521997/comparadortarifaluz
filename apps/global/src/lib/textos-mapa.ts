import type { Idioma } from "./textos";

type Comb = "g95" | "e10" | "g98" | "diesel" | "dieselPremium" | "glp" | "e85" | "gnc";

export interface DatosLead { n: string; enX: string; G: string; g: string; d: string; dArt: string; gArt: string }
export interface DatosBarata { cArt: string; enX: string; sitio: string; lugar: string; precio: string; media: string }

export interface TextosMapa {
  slug: string;
  indiceT: string;
  /** nombres: «Frankreich, Spanien und Portugal»; enes: «en France, en Espagne et au Portugal» */
  indiceLead: (nombres: string, enes: string) => string;
  titulo: (enX: string) => string;
  tituloSeo: (enX: string) => string;
  lead: (o: DatosLead) => string;
  /** Nombre del carburante (botones, tablas) y forma para usar dentro de una frase (con artículo si hace falta). */
  comb: Record<Comb, string>;
  combArt: Record<Comb, string>;
  buscar: string;
  placeholder: string;
  cerca: string;
  combustible: string;
  baratasZona: string;
  vacio: string;
  ruta: string;
  precioDel: (fecha: string) => string;
  autopista: string;
  sinDatos: string;
  sinUbicacion: string;
  cargando: string;
  barato: string;
  caro: string;
  estacion: string;
  lugares: string;
  estaciones: (n: number, s: string) => string;
  nada: string;
  /** Avisos de MapLibre para mover el mapa sin atrapar el scroll: Windows/Linux, Mac y móvil. */
  gestos: [string, string, string];
  baratasT: (c: string, cArt: string, enX: string) => string;
  colEstacion: string;
  colLugar: string;
  colPrecio: string;
  statN: string;
  statMedia: (c: string) => string;
  statMin: (c: string) => string;
  autopistaFrase: (cArt: string, pct: string, a: string, r: string) => string;
  pBarata: (cArt: string, enX: string) => string;
  rBarata: (o: DatosBarata) => string;
  pActual: string;
  rActual: (fuente: string, hora: string) => string;
  pAutopista: string;
  /** A quién comunican los precios las gasolineras de cada país (va detrás del verbo de rActual). */
  fuentes: Record<"FR" | "ES" | "IT" | "PT", string>;
  aviso: string;
  /** Nota bajo las cifras cuando no cuentan las islas ni ultramar. */
  notaContinente: string;
  otrosMapas: string;
  boton: string;
  app: TextosApp;
}

/** Pestañas «más baratas / más cercanas / en mi ruta», planificador de ruta y modo pantalla completa. */
export interface TextosApp {
  pestBaratas: string;
  pestCerca: string;
  pestRuta: string;
  cercaTi: string;
  cercaDe: (lugar: string) => string;
  cercaCentro: string;
  /** Resumen sobre la lista de las más cercanas: la más barata de ellas. */
  laMasBarata: (nombre: string, precio: string, dist: string) => string;
  desde: string;
  hasta: string;
  miUbicacion: string;
  origenPh: string;
  destinoPh: string;
  desvio: string;
  calcular: string;
  quitar: string;
  calculando: string;
  rutaError: string;
  rutaFalta: string;
  /** «Ruta de 220 km: 85 gasolineras a menos de 2 km de la carretera.» */
  rutaResumen: (km: string, n: string, desvio: string) => string;
  rutaNada: string;
  porPrecio: string;
  porPaso: string;
  /** Punto de la ruta («km 120») */
  km: (km: string) => string;
  /** Distancia («a 1,2 km») */
  a: (dist: string) => string;
  masBarata: string;
  pantalla: string;
  cerrar: string;
  lista: string;
  ocultar: string;
  ficha: string;
  /** Abrir en Google Maps una ruta con la gasolinera como parada (salida → gasolinera → destino). */
  conParada: string;
  /** Etiqueta de la ruta alternativa más rápida */
  rapida: string;
  elegirRuta: string;
  /** Parada intermedia opcional de la ruta (Madrid → Albacete → Valencia) */
  anadirParada: string;
  por: string;
  paradaPh: string;
}

